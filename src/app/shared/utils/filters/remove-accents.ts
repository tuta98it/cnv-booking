export function removeAccents(source: string): string {
  if (typeof source !== 'string') {
    // Xử lý trường hợp biến source không phải chuỗi (nếu cần)
    return '';
  }

  const withAccents = 'ÀÁÂÃÈÉÊÌÍÒÓÔÕÙÚÝàáâãèéêìíòóôõùúýĂăĐđĨĩŨũƠơƯưẠạẢảẤấẦầẨẩẪẫẬậẮắẰằẲẳẴẵẶặẸẹẺẻẼẽẾếỀềỂểỄễỆệỈỉỊịỌọỎỏỐốỒồỔổỖỗỘộỚớỜờỞởỠỡỢợỤụỦủỨứỪừỬửỮữỰựỲỳỴỵỶỷỸỹ';
  const withoutAccents = 'AAAAEEEIIOOOOUUYaaaaeeeiioooouuyAaDdIiUuOoUuAaAaAaAaAaAaAaAaAaAaAaAaEeEeEeEeEeEeEeEeIiIiOoOoOoOoOoOoOoOoOoOoOoOoUuUuUuUuUuUuUuYyYyYyYy';

  const result = source.split('').map((char: any) => {
    const index = withAccents.indexOf(char);
    return index !== -1 ? withoutAccents[index] : char;
  }).join('');

  return result;
}
